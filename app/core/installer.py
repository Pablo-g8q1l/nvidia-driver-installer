@dataclass
class InstallOptions:
    """Installation parameters chosen by the user in the GUI."""

    method: str                 # "nvk" | "repo" | "run"
    distro: DistroInfo
    open_modules: bool = False  # open kernel modules (Turing+)
    run_version: str = ""       # version for the "run" method, e.g. "580.95.05"
    repo_package: str = ""      # package for Kubuntu/Mint, e.g. "nvidia-driver-580"
    repo_source: str = ""       # plain Debian: "debian" (non-free) | "nvidia"
    use_backports: bool = False  # NVK on plain Debian with RTX 50xx
    boot_report: bool = False   # boot report service (opt-in from Settings)


# Runs a script supplied on standard input (the pkexec path).
# Root rewrites the script from the pipe into its OWN temporary file (0600,
# root) and only then executes it — the contents cannot be swapped between
# authorization and execution (TOCTOU), as they could with a user file in
# /tmp. Executing from a file (not `bash -s`) leaves stdin at EOF, so no step
# will "eat" the rest of the script if it happens to read standard input.
_ROOT_RUNNER = (
    'tmp="$(mktemp)" && cat > "$tmp" && bash "$tmp"; rc=$?; rm -f "$tmp"; exit $rc'
)

# Header of every generated script — helper functions and non-interactive mode
_SCRIPT_HEADER = """#!/bin/bash
# Script generated automatically by NVIDIA Driver Installer.
set -o pipefail
export DEBIAN_FRONTEND=noninteractive
step() { echo "@STEP@ $1"; }
error() { echo "@ERROR@ $1"; exit 1; }
"""

