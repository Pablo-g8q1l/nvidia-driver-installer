# Fedora: the nouveau module lives in the kernel-modules package, which may be
# missing — installing akmod-nvidia can pull in a new kernel only partially
# (kernel-core and kernel-devel as dependencies, without kernel-modules). After
# switching to NVK such a kernel comes up with no GPU driver at all. Install
# kernel-modules for every installed kernel that is missing nouveau.
_NOUVEAU_KERNEL_MODULES_FEDORA = """for k in /lib/modules/*/; do
  k="$(basename "$k")"
  [ -e "/lib/modules/$k/vmlinuz" ] || continue
  modinfo -k "$k" nouveau >/dev/null 2>&1 && continue
  dnf -y install "kernel-modules-$k" || echo "WARNING: failed to install the kernel-modules-$k package"
done
true"""

# Nobara: its own repository (nobara-nvidia-production) provides akmod-nvidia
# in a version newer than RPMFusion, but userspace is packaged the negativo17
# way (nvidia-driver*), not the RPMFusion way (xorg-x11-drv-nvidia*). The fixed
# list "akmod-nvidia xorg-x11-drv-nvidia-cuda" then mixes two stacks: the kernel
# module comes from the distribution repo (the higher version wins), the CUDA
# libraries from RPMFusion (the only provider of that name), and the actual GL
# driver (libGLX_nvidia) is not installed at all — the desktop falls back to
# llvmpipe, nvidia-smi reports "Driver/library version mismatch" (the Nobara 43
# case, 2026-07-03). We condition the package set on the repository state, not
# the distribution name: if the latest akmod-nvidia has an nvidia-driver
# counterpart in the same version, and xorg-x11-drv-nvidia in that version does
# not exist, we install the native set (first removing any xorg-x11-drv-nvidia*
# leftovers — the same files under different package names cause conflicts). On
# plain Fedora nvidia-driver does not exist in any repository, the condition
# does not hold and the set stays exactly as before.
_FEDORA_REPO_INSTALL = """PKGS="akmod-nvidia xorg-x11-drv-nvidia-cuda"
AKMOD_V="$(dnf -q repoquery --qf '%{version}\\n' akmod-nvidia 2>/dev/null | sort -V | tail -n1)"
if [ -n "$AKMOD_V" ] \\
   && dnf -q repoquery --qf '%{version}\\n' nvidia-driver 2>/dev/null | grep -qxF "$AKMOD_V" \\
   && ! dnf -q repoquery --qf '%{version}\\n' xorg-x11-drv-nvidia 2>/dev/null | grep -qxF "$AKMOD_V"; then
  echo "The distribution repository packages the driver as nvidia-driver ($AKMOD_V) — installing the native set"
  PKGS="akmod-nvidia nvidia-driver nvidia-driver-cuda"
  dnf -y remove 'xorg-x11-drv-nvidia*' 2>/dev/null || true
fi
dnf -y install $PKGS || error "Instalacja pakietów nie powiodła się\""""

# Kernel built with Clang and LTO (e.g. CachyOS with ThinLTO): the .run
# installer's own module build compiles LLVM bitcode (it detects CC itself from
# CONFIG_CC_VERSION_TEXT), but its Makefile has `LD ?= ld` and passes
# `"LD=$(LD)"` to kbuild, so linking is done by GNU ld and fails
# ("/usr/bin/ld: unrecognised emulation mode: llvm"). Thanks to `?=` the
# environment LD=ld.lld takes precedence; LLVM=1 switches the rest of the kbuild
# tools (llvm-ar/nm/objcopy), and IGNORE_CC_MISMATCH=1 disables the compiler
# version comparison, which is confused by the ", LLD" suffix in such a kernel's
# CONFIG_CC_VERSION_TEXT. The LLVM tools are guaranteed: the headers of a kernel
# built with Clang depend on clang/llvm/lld. dkms detects Clang kernels itself
# (grep CONFIG_CC_IS_CLANG per kernel), which is why we pass the variables via
# `env` only to the .run installer, and don't export them to further steps. On a
# kernel built with GCC (plain Arch, Debian, Fedora, Mint) the condition does
# not hold, NV_TOOLCHAIN_ENV stays empty and nothing changes.
_LLVM_KERNEL_ENV = """NV_TOOLCHAIN_ENV=""
if grep -qs '^CONFIG_CC_IS_CLANG=y' "/lib/modules/$(uname -r)/build/.config"; then
  echo "Kernel built with Clang/LLVM — the module will be built with the LLVM toolchain"
  NV_TOOLCHAIN_ENV="LLVM=1 LD=ld.lld OBJDUMP=llvm-objdump IGNORE_CC_MISMATCH=1"
fi"""

# The .run installer builds the DKMS module only for the running kernel. When
# GRUB boots a different kernel by default (e.g. installing from an older one
# while the newest is the default), the system would come up without a driver
# and without nouveau (blacklisted) — the desktop would fall back to CPU
# rendering. Build the module for every kernel that has headers.
_DKMS_ALL_KERNELS = """for k in /lib/modules/*/; do
  k="$(basename "$k")"
  [ "$k" = "$(uname -r)" ] && continue
  [ -e "/lib/modules/$k/build" ] || continue
  dkms autoinstall -k "$k" || echo "WARNING: building the DKMS module for kernel $k failed"
done
true"""

# Arch: fixing "ghost packages" — a package is listed in the pacman database,
# but its files were deleted from disk outside pacman (e.g. cleanup after a .run
# driver by another tool). `pacman -S --needed` won't touch such a package, and
# without the libnvidia-egl-* libraries the GBM EGL platform doesn't come up and
# the desktop falls back to a TTY, even though the installation and kernel
# module are correct (the CachyOS case, 2026-07-03: no libnvidia-egl-gbm.so.1
# with egl-gbm "installed"). On a healthy system the step only reads state
# (`pacman -Qk`) and changes nothing. The -Qk result is logged unconditionally
# for every package: on 2026-07-04 the step reported nothing in real runs
# despite files missing on disk — since then the installation log always
# documents the observed package state.
_ARCH_VERIFY_EGL_PACKAGES = """for p in nvidia-utils egl-gbm egl-wayland egl-wayland2 egl-x11 eglexternalplatform libglvnd; do
  if ! pacman -Qq "$p" >/dev/null 2>&1; then
    echo "Package $p: not installed"
    continue
  fi
  stan="$(LANG=C pacman -Qk "$p" 2>/dev/null)"
  echo "Package ${stan:-$p: pacman -Qk gave no response}"
  if echo "$stan" | grep -qE ', [1-9][0-9]* missing'; then
    echo "Package $p has missing files on disk — reinstalling"
    pacman -S --noconfirm "$p" || error "Naprawa pakietu nie powiodła się ($p)"
  fi
done
true"""

