def _steps_repo(opts: InstallOptions, keyring: str = "") -> list[tuple[str, str]]:
    """Installation from the distribution repository (or the official NVIDIA repo)."""
    fam = opts.distro.family
    steps: list[tuple[str, str]] = []

    # The .run-file driver must be removed BEFORE installing packages.
    # Otherwise distribution mechanisms (e.g. nvidia-installer-cleanup on
    # Ubuntu) will fire nvidia-uninstall during unpacking and delete files
    # that the packages have just installed (including glvnd 10_nvidia.json),
    # causing the desktop to fall back to CPU software rendering.
    steps.append((
        "Usuwanie sterownika z pliku .run (jeśli obecny)",
        "if [ -x /usr/bin/nvidia-uninstall ]; then"
        " nvidia-uninstall --silent || true; fi\ntrue",
    ))

    if fam == "arch":
        pkg = "nvidia-open-dkms" if opts.open_modules else "nvidia-dkms"
        steps.append((
            "Usuwanie konfliktującej odmiany sterownika",
            "for p in nvidia nvidia-lts nvidia-open nvidia-open-dkms nvidia-dkms; do\n"
            '  pacman -Qq "$p" >/dev/null 2>&1 && pacman -Rdd --noconfirm "$p"\n'
            "done; true",
        ))
        steps.append((
            "Instalacja sterownika z repozytorium (pełna aktualizacja systemu)",
            f"{_ARCH_KERNEL_HEADERS}\n"
            f"pacman -Syu --noconfirm --needed {pkg} nvidia-utils nvidia-settings"
            ' "${KERNEL_PKG}-headers"'
            ' || error "Instalacja pakietów nie powiodła się"',
        ))
        steps.append((
            "Kontrola integralności pakietów EGL (naprawa brakujących plików)",
            _ARCH_VERIFY_EGL_PACKAGES,
        ))

    elif fam == "fedora":
        # RPMFusion only when no enabled repository already provides
        # akmod-nvidia — distributions with their own driver repo
        # (e.g. Nobara) keep theirs, plain Fedora gets RPMFusion
        steps.append((
            "Włączanie repozytorium RPMFusion (free + nonfree)",
            "if dnf -q repoquery --qf '%{name}\\n' akmod-nvidia 2>/dev/null | grep -q .; then\n"
            '  echo "A repository with the NVIDIA driver is already available — skipping RPMFusion"\n'
            "else\n"
            '  dnf -y install'
            ' "https://mirrors.rpmfusion.org/free/fedora/rpmfusion-free-release-$(rpm -E %fedora).noarch.rpm"'
            ' "https://mirrors.rpmfusion.org/nonfree/fedora/rpmfusion-nonfree-release-$(rpm -E %fedora).noarch.rpm"'
            " || true\nfi\ntrue",
        ))
        if opts.open_modules:
            # RPMFusion macro switching akmod-nvidia to open modules;
            # it must exist before akmods builds the module
            steps.append((
                "Włączanie otwartych modułów jądra (makro RPMFusion)",
                "printf '%%_with_kmod_nvidia_open 1\\n' > /etc/rpm/macros.nvidia-kmod"
                ' || error "Nie udało się zapisać makra RPM"',
            ))
        steps.append((
            "Instalacja sterownika (akmod-nvidia)",
            _FEDORA_REPO_INSTALL,
        ))
        steps.append((
            "Budowanie modułu jądra (akmods — może potrwać kilka minut)",
            'akmods --force || error "Budowanie modułu jądra nie powiodło się"',
        ))

    else:  # debian family
        if opts.distro.ubuntu_based:
            pkg = opts.repo_package or "nvidia-driver-580"
            steps.append((
                "Odświeżanie listy pakietów",
                'apt-get update || error "apt-get update nie powiodło się"',
            ))
            steps.append((
                f"Instalacja sterownika ({pkg})",
                f'apt-get -y install {pkg} || error "Instalacja pakietu nie powiodła się ({pkg})"',
            ))
        elif opts.repo_source == "nvidia":
            # Plain Debian, the official NVIDIA repository — the only package
            # source for RTX 50xx cards (the Debian repo ends at 550).
            # Debian and NVIDIA packages must not mix, hence the cleanup.
            pkg = "nvidia-open" if opts.open_modules else "cuda-drivers"
            steps.append((
                "Odinstalowanie sterownika z repozytorium Debiana (jeśli obecny)",
                _removal_commands("debian"),
            ))
            steps.append((
                "Dodawanie oficjalnego repozytorium NVIDIA (cuda-keyring)",
                f'apt-get -y install "{keyring}"'
                ' || error "Instalacja pakietu cuda-keyring nie powiodła się"\n'
                'apt-get update || error "apt-get update nie powiodło się"',
            ))
            steps.append((
                f"Instalacja sterownika z repozytorium NVIDIA ({pkg})",
                f"apt-get -y install linux-headers-amd64 {pkg}"
                f' || error "Instalacja pakietu nie powiodła się ({pkg})"',
            ))
        else:
            steps.append((
                "Odinstalowanie sterownika z repozytorium NVIDIA (jeśli obecny)",
                _removal_commands("debian") + "\n" + _REMOVE_NVIDIA_REPO,
            ))
            steps.append((
                "Włączanie sekcji contrib / non-free / non-free-firmware",
                # Debian may use the classic sources.list or the deb822 format
                _DEBIAN_NONFREE_SECTIONS,
            ))
            steps.append((
                "Instalacja sterownika (nvidia-driver)",
                "apt-get -y install nvidia-driver firmware-misc-nonfree"
                " linux-headers-amd64"
                ' || error "Instalacja pakietów nie powiodła się"',
            ))

    # Common configuration after installing from the repository
    steps.append(("Konfiguracja modprobe (blokada nouveau, modeset)", _MODPROBE_CONFIG))
    steps.append(_initramfs_step(opts.distro))
    return steps


def _steps_nvk(opts: InstallOptions) -> list[tuple[str, str]]:
    """Switching to the open NVK / Mesa driver (nouveau)."""
    fam = opts.distro.family
    extra: list[tuple[str, str]] = []  # extra steps depending on the distribution
    if fam == "arch":
        install = (
            "pacman -Syu --noconfirm --needed mesa vulkan-nouveau vulkan-icd-loader"
            ' vulkan-tools || error "Instalacja pakietów Mesa nie powiodła się"'
        )
        firmware = (
            "pacman -S --noconfirm --needed linux-firmware"
            ' || error "Instalacja pakietu linux-firmware nie powiodła się"'
        )
    elif fam == "fedora":
        extra.append((
            "Uzupełnianie modułu nouveau (pakiet kernel-modules)",
            _NOUVEAU_KERNEL_MODULES_FEDORA,
        ))
        install = (
            "dnf -y install mesa-vulkan-drivers mesa-dri-drivers vulkan-tools"
            ' || error "Instalacja pakietów Mesa nie powiodła się"'
        )
        firmware = (
            "dnf -y install nvidia-gpu-firmware"
            ' || error "Instalacja pakietu nvidia-gpu-firmware nie powiodła się"'
        )
    elif opts.use_backports and not opts.distro.ubuntu_based:
        # Plain Debian with an RTX 50xx (Blackwell) card: the stable release is
        # too old in three places at once — the kernel (nouveau without GB20x),
        # Mesa < 25.2 (NVK without Blackwell) and firmware without GSP r570.
        # All three components come from the official backports.
        extra.append((
            "Włączanie oficjalnych backportów Debiana",
            ". /etc/os-release\n"
            'BP="${VERSION_CODENAME}-backports"\n'
            'if ! apt-cache policy | grep -q "$BP"; then\n'
            '  echo "deb http://deb.debian.org/debian ${BP} main contrib'
            ' non-free non-free-firmware"'
            " > /etc/apt/sources.list.d/nvidia-installer-backports.list\n"
            "fi\n" + _DEBIAN_NONFREE_SECTIONS,
        ))
        extra.append((
            "Instalacja nowszego jądra z backportów (wymagane dla RTX 50xx)",
            'apt-get -y -t "$BP" install linux-image-amd64'
            ' || error "Instalacja jądra z backportów nie powiodła się"',
        ))
        # libgl1-mesa-dri from the same version as the Vulkan driver —
        # mixing Mesa versions (GL 25.0 + Vulkan 25.2) breaks the desktop
        install = (
            'apt-get -y -t "$BP" install mesa-vulkan-drivers libgl1-mesa-dri'
            " mesa-utils vulkan-tools"
            ' || error "Instalacja pakietów Mesa z backportów nie powiodła się"'
        )
        firmware = (
            'apt-get -y -t "$BP" install firmware-nouveau'
            ' || apt-get -y -t "$BP" install firmware-misc-nonfree'
            ' || error "Instalacja firmware nouveau nie powiodła się"'
        )
    else:
        install = (
            "apt-get update || true\n"
            "apt-get -y install mesa-vulkan-drivers mesa-utils vulkan-tools"
            ' || error "Instalacja pakietów Mesa nie powiodła się"'
        )
        if opts.distro.ubuntu_based:
            firmware = (
                "apt-get -y install linux-firmware"
                ' || error "Instalacja pakietu linux-firmware nie powiodła się"'
            )
        else:
            # Plain Debian: nouveau firmware lives in the non-free-firmware section;
            # older releases don't know the firmware-nouveau package
            firmware = (
                _DEBIAN_NONFREE_SECTIONS + "\n"
                "apt-get -y install firmware-nouveau"
                " || apt-get -y install firmware-misc-nonfree"
                ' || error "Instalacja firmware nouveau nie powiodła się"'
            )
    return [
        ("Odinstalowanie sterownika NVIDIA (jeśli obecny)", _removal_commands(fam)),
        ("Usuwanie blokady nouveau i konfiguracji NVIDIA", _REMOVE_MODPROBE_CONFIG),
        ("Usuwanie wymuszeń NVIDIA w zmiennych środowiskowych", _REMOVE_GL_ENV),
        ("Usuwanie parametrów nvidia-drm z konfiguracji GRUB", _REMOVE_KERNEL_PARAMS),
        *extra,
        ("Instalacja sterownika NVK / Mesa", install),
        (
            "Instalacja firmware GPU (GSP — wymagany na kartach RTX)",
            firmware + "\n" + _GSP_FIRMWARE_CHECK + "\n" + _NOUVEAU_MODULE_CHECK,
        ),
        _initramfs_step(opts.distro),
    ]


def _steps_run(opts: InstallOptions, runfile: str) -> list[tuple[str, str]]:
    """Installation from a downloaded NVIDIA .run file."""
    fam = opts.distro.family
    if fam == "arch":
        deps = (
            f"{_ARCH_KERNEL_HEADERS}\n"
            "pacman -Syu --noconfirm --needed base-devel dkms"
            ' "${KERNEL_PKG}-headers"'
            ' || error "Instalacja zależności nie powiodła się"'
        )
    elif fam == "fedora":
        deps = (
            "dnf -y install gcc make dkms kernel-devel kernel-headers"
            " libglvnd-devel libglvnd-glx libglvnd-opengl"
            ' || error "Instalacja zależności nie powiodła się"'
        )
    else:
        deps = (
            'apt-get update || error "apt-get update nie powiodło się"\n'
            'apt-get -y install build-essential dkms "linux-headers-$(uname -r)"'
            " libglvnd-dev pkg-config"
            ' || error "Instalacja zależności nie powiodła się"'
        )

    # Open-modules flag depending on the driver version
    open_flag = (
        nvidia_versions.open_module_flag(opts.run_version) if opts.open_modules else ""
    )
    # A loaded nvidia module (.run installation with the driver running,
    # e.g. changing the version from a repository driver): the 595.84 installer
    # then asks to skip the check and in --silent mode ABORTS by default
    # ("Answer: Abort installation" — the EndeavourOS 2026-07-05 case).
    # Consent is given upfront with --allow-installation-with-running-driver;
    # older installers (including Legacy branches) don't know this flag, so the
    # condition checks the actual state (the module in /proc/modules) AND the
    # installer's capabilities (the flag in --advanced-options). With the nvidia
    # module inactive — the nouveau/NVK path, on which previous cycles passed —
    # the variable stays empty and the command is as before.
    allow_running = (
        'NV_ALLOW_RUNNING=""\n'
        "if grep -q '^nvidia ' /proc/modules"
        f' && sh "{runfile}" --advanced-options 2>/dev/null'
        " | grep -q -- --allow-installation-with-running-driver; then\n"
        '  echo "The nvidia module is loaded — passing the installer consent'
        ' to install with the driver running"\n'
        '  NV_ALLOW_RUNNING="--allow-installation-with-running-driver"\n'
        "fi"
    )
    return [
        ("Instalacja zależności do budowania modułu jądra", deps),
        ("Odinstalowanie poprzednich sterowników", _removal_commands(fam)),
        ("Konfiguracja modprobe (blokada nouveau, modeset)", _MODPROBE_CONFIG),
        (
            "Instalacja sterownika NVIDIA z pliku .run (może potrwać kilka minut)",
            # The installation happens from a running desktop, so nouveau (or
            # the old nvidia module) still holds the card: --no-nouveau-check
            # then doesn't abort the installation, and --skip-module-load skips
            # the trial module load, which would fail. The nouveau blacklist is
            # already written, so after a restart nvidia will claim the card.
            _LLVM_KERNEL_ENV + "\n" + allow_running + "\n"
            f'env $NV_TOOLCHAIN_ENV sh "{runfile}" --silent --accept-license --dkms --no-x-check'
            f' --no-nouveau-check --skip-module-load $NV_ALLOW_RUNNING{open_flag}'
            ' || error "Instalator NVIDIA zwrócił błąd — szczegóły w /var/log/nvidia-installer.log"',
        ),
        ("Budowanie modułu DKMS dla pozostałych jąder", _DKMS_ALL_KERNELS),
        _initramfs_step(opts.distro),
    ]


def build_plan(
    opts: InstallOptions, runfile: str = "", keyring: str = ""
) -> tuple[list[str], str]:
    """Builds the installation plan: (list of step labels, bash script content)."""
    if opts.method == "repo":
        steps = _steps_repo(opts, keyring)
    elif opts.method == "nvk":
        steps = _steps_nvk(opts)
    elif opts.method == "run":
        steps = _steps_run(opts, runfile)
    else:
        raise ValueError(f"Nieznana metoda instalacji: {opts.method}")

    # A common, purely diagnostic step at the end of every method — see the
    # comment near _BOOT_REPORT_STEP. Opt-in: when the option is disabled the
    # installation cleans up the service from earlier installations.
    steps.append(_BOOT_REPORT_STEP if opts.boot_report else _BOOT_REPORT_REMOVE_STEP)

    lines = [_SCRIPT_HEADER]
    for label, cmds in steps:
        lines.append(f'step "{label}"')
        lines.append(cmds)
    lines.append('echo "@SUCCESS@"')
    return [s[0] for s in steps], "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Thread that runs the installation (download + script via pkexec)
# ---------------------------------------------------------------------------

class InstallThread(QThread):
    """Runs the whole installation in the background, reporting progress via Qt signals."""

    sig_log = Signal(str)            # next log line
    sig_step = Signal(int, int, str)  # step number, step count, label
    sig_download = Signal(int)       # .run file download percentage
    sig_finished = Signal(bool, str)  # success?, final message

    def __init__(self, opts: InstallOptions, sudo_password: str = "", parent=None):
        super().__init__(parent)
        self.opts = opts
        # Fallback when the system has no pkexec: password for sudo -S,
        # fetched and verified earlier by the GUI (never goes to the logs)
        self._sudo_password = sudo_password

    # ---- downloading the .run file ---------------------------------------
    def _verify_runfile(self, path: str) -> bool:
        """Checks the .run installer's built-in checksum (without root).

        Catches files truncated during download (e.g. a hard kill of the
        program leaves a > 50 MB file in the cache that looks complete)
        as well as ones corrupted or swapped along the way.
        """
        self.sig_log.emit(tr("Sprawdzanie integralności pliku .run..."))
        code, _, _ = utils.run(["sh", path, "--check"], timeout=300)
        return code == 0

    def _download_runfile(self) -> str:
        """Downloads the .run file to the cache; returns the file path."""
        import requests

        ver = self.opts.run_version
        url = nvidia_versions.download_url(ver)
        dest = utils.CACHE_DIR / f"NVIDIA-Linux-x86_64-{ver}.run"

        # File already downloaded earlier — use the copy if it passes the check
        if dest.exists() and dest.stat().st_size > 50_000_000:
            if self._verify_runfile(str(dest)):
                self.sig_log.emit(
                    tr("Plik {n} już pobrany — używam kopii lokalnej")
                    .format(n=dest.name)
                )
                self.sig_download.emit(100)
                return str(dest)
            self.sig_log.emit(tr("Kopia lokalna uszkodzona — pobieram ponownie"))
            dest.unlink(missing_ok=True)

        self.sig_log.emit(tr("Pobieranie:") + f" {url}")
        try:
            r = requests.get(
                url,
                stream=True,
                timeout=60,
                headers={"User-Agent": "Mozilla/5.0 (nvidia-installer-gui)"},
            )
            r.raise_for_status()
            total = int(r.headers.get("content-length", 0))
            done = 0
            with open(dest, "wb") as f:
                for chunk in r.iter_content(chunk_size=256 * 1024):
                    f.write(chunk)
                    done += len(chunk)
                    if total:
                        self.sig_download.emit(int(done * 100 / total))
        except Exception:
            # We don't leave an incomplete file in the cache
            dest.unlink(missing_ok=True)
            raise
        if not self._verify_runfile(str(dest)):
            dest.unlink(missing_ok=True)
            raise RuntimeError(
                tr("Pobrany plik .run nie przechodzi kontroli integralności"
                   " — spróbuj ponownie")
            )
        self.sig_log.emit(
            tr("Pobrano:") + f" {dest} ({dest.stat().st_size // (1024*1024)} MB)"
        )
        return str(dest)

    def _download_keyring(self) -> str:
        """Downloads the cuda-keyring package (NVIDIA repo); returns the file path."""
        import requests

        url = nvidia_versions.keyring_url(self.opts.distro)
        dest = utils.CACHE_DIR / url.rsplit("/", 1)[-1]
        if dest.exists() and dest.stat().st_size > 1000:
            self.sig_log.emit(
                tr("Plik {n} już pobrany — używam kopii lokalnej").format(n=dest.name)
            )
            return str(dest)
        self.sig_log.emit(tr("Pobieranie:") + f" {url}")
        try:
            r = requests.get(
                url,
                timeout=60,
                headers={"User-Agent": "Mozilla/5.0 (nvidia-installer-gui)"},
            )
            r.raise_for_status()
            dest.write_bytes(r.content)
        except Exception:
            dest.unlink(missing_ok=True)
            raise
        return str(dest)

    # ---- the thread's main work ------------------------------------------
    def run(self):  # noqa: D102 — QThread method
        log_lines: list[str] = []

        def log(text: str) -> None:
            log_lines.append(text)
            self.sig_log.emit(text)

        ok = False
        err_msg = ""
        try:
            if not utils.is_linux():
                raise RuntimeError(tr("Instalacja działa tylko na Linuksie"))
            use_sudo = False
            if not utils.which("pkexec"):
                # Fallback path without polkit: sudo with the password from the GUI
                if utils.which("sudo") and self._sudo_password:
                    use_sudo = True
                else:
                    raise RuntimeError(
                        tr("Brak poleceń pkexec i sudo — zainstaluj pakiet pkexec"
                           " (polkit) lub sudo")
                    )

            # 1. The .run method requires downloading the installer first,
            #    and the NVIDIA repo on Debian — the cuda-keyring package
            runfile = keyring = ""
            if self.opts.method == "run":
                log(tr("Wersja sterownika:") + f" {self.opts.run_version}")
                runfile = self._download_runfile()
            elif self.opts.method == "repo" and self.opts.repo_source == "nvidia":
                keyring = self._download_keyring()

            # 2. Generate the installation script
            steps, script = build_plan(self.opts, runfile, keyring)
            log(tr("Liczba kroków:") + f" {len(steps)}")

            # 3. Run as root — a single password prompt.
            #    Normally pkexec (the polkit window): the script goes through a
            #    pipe straight to root (_ROOT_RUNNER), without a file in /tmp
            #    whose content another process could swap before execution.
            #    Fallback sudo -S: the pipe carries the password (-p "" disables
            #    the text prompt), so the script must go via a temporary file —
            #    a path tested on Debian without polkit, kept.
            if use_sudo:
                with tempfile.NamedTemporaryFile(
                    "w", suffix=".sh", prefix="nvidia-installer-",
                    delete=False, encoding="utf-8",
                ) as f:
                    f.write(script)
                    script_path = f.name
                os.chmod(script_path, 0o700)
                log(tr("Skrypt instalacyjny:") + f" {script_path}")
                cmd = ["sudo", "-S", "-k", "-p", "", "bash", script_path]
            else:
                log(tr("Skrypt instalacyjny przekazany potokiem (bez pliku w /tmp)"))
                cmd = ["pkexec", "bash", "-c", _ROOT_RUNNER]
            proc = subprocess.Popen(
                cmd,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                bufsize=1,
            )
            if use_sudo:
                proc.stdin.write(self._sudo_password + "\n")
                proc.stdin.flush()
                proc.stdin.close()
            else:
                # The script fits in the pipe buffer — the write won't block
                # the thread even while the polkit authorization window awaits the password
                proc.stdin.write(script)
                proc.stdin.close()
            idx = 0
            success_marker = False
            for line in proc.stdout:
                line = line.rstrip("\n")
                if line.startswith("@STEP@"):
                    idx += 1
                    label = line[len("@STEP@"):].strip()
                    self.sig_step.emit(idx, len(steps), label)
                    # Translate the marker for the log (the step indicator is
                    # translated separately in the GUI via tr_prefix)
                    line = "@STEP@ " + tr_prefix(label)
                elif line.startswith("@ERROR@"):
                    # Error text goes both to the log and the final dialog,
                    # translated to the interface language
                    err_msg = tr_prefix(line[len("@ERROR@"):].strip())
                    line = "@ERROR@ " + err_msg
                elif line.strip() == "@SUCCESS@":
                    success_marker = True
                log(line)
            code = proc.wait()
            ok = code == 0 and success_marker

            if not ok and not err_msg:
                if code in (126, 127):
                    err_msg = tr("Anulowano autoryzację administratora (pkexec)")
                else:
                    err_msg = tr("Skrypt zakończył się kodem") + f" {code}"
        except Exception as e:
            err_msg = str(e)
            log(tr("BŁĄD:") + f" {err_msg}")

        # 4. Add an installation history entry with the full log
        wersja = (
            self.opts.run_version
            or self.opts.repo_package
            or ("NVK / Mesa" if self.opts.method == "nvk"
                else "repozytorium NVIDIA" if self.opts.repo_source == "nvidia"
                else "repozytorium")
        )
        try:
            history.add_entry(
                metoda=self.opts.method,
                wersja=wersja,
                dystrybucja=self.opts.distro.name,
                status="sukces" if ok else "błąd",
                log_text="\n".join(log_lines),
            )
        except Exception:
            pass  # a history-write problem must not ruin the result

        self.sig_finished.emit(ok, err_msg)
